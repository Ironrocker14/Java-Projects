
public class Patient
{
	int id, age;
	String name, gender, disease, appointment;
	
	Patient(int id, int age, String name, String gender, String disease, String appointment)
	{
		this.id = id;
		this.age = age;
		this.name = name;
		this.gender = gender;
		this.disease = disease;
		this.appointment = appointment;
		
	}
	
}
